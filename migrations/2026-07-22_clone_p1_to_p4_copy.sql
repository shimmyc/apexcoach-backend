-- ── 8b. profile-row payload (profile_data + briefs + roadmap + body) ────────
-- profile_data is REPLACED WHOLESALE, never merged: profile 4 has its own 6
-- goals / 2 injuries / schedule, and merging would leave the v2 planner reading
-- 12 goals, half of them fictional.
--
-- Three identity keys are stripped on the way across, per the SKIP bucket:
--   - avatar_image  (profile 1's base64 photo)
--   - avatar_color
--   - name          (re-set to profile 4's OWN top-level name; the key must
--                    exist because fetchAI() hard-returns on a missing
--                    currentProfileData.name)
-- Everything else in profile_data comes over intact: goals (with their ids and
-- per-goal roadmaps), injuries, schedule, focus_override, ai_prompt_context,
-- equipment, philosophy, belt/martial-arts keys, settings.
UPDATE profiles p4
SET profile_data = (p1.profile_data - 'avatar_image' - 'avatar_color')
                     || jsonb_build_object('name', p4.name),
    coaching_brief              = p1.coaching_brief,
    historical_brief            = p1.historical_brief,
    historical_brief_updated_at = p1.historical_brief_updated_at,
    roadmap_data                = p1.roadmap_data,
    roadmap_data_updated_at     = p1.roadmap_data_updated_at,
    height_inches               = p1.height_inches,
    birth_date                  = p1.birth_date,
    sex                         = p1.sex,
    goal_weight_lbs             = p1.goal_weight_lbs,
    goal_weight_timeline_months = p1.goal_weight_timeline_months,
    gym_access                  = p1.gym_access,
    gym_type                    = p1.gym_type
FROM profiles p1
WHERE p4.id = 4 AND p1.id = 1;


-- ============================================================================
-- ── 9. MANDATORY: advance the shared identity sequences ─────────────────────
-- ============================================================================
-- READ THIS BEFORE SKIPPING IT.
--
-- These sequences are SHARED across every profile. The inserts above wrote ids
-- in the 100,000+ range without consuming sequence values, so each sequence is
-- still sitting at ~its pre-clone position. Left alone, profile 1's next real
-- workout/exercise/sleep row keeps drawing small ids — which is fine today, but
-- the sequence will eventually climb into the cloned range and collide with a
-- profile 4 row, producing a duplicate-key failure on a REAL user's save.
--
-- setval() to MAX(id) makes the next value land safely above every cloned row.
-- pg_get_serial_sequence works for BOTH flavours present here (confirmed by the
-- Section A2 baseline): plain nextval sequences on workouts/exercises/
-- daily_checkins, and GENERATED ALWAYS identities on daily_sleep/daily_steps/
-- body_metrics/micro_goals/workout_templates. All eight are covered below.
--
-- HARDENED AGAINST A SILENT NO-OP. setval() is a STRICT function: given a NULL
-- sequence name it returns NULL and does nothing, without raising. So if any of
-- these sequences is not OWNED BY its column (possible for a column defined as
-- `bigint DEFAULT nextval('seq')` rather than as a real `serial`),
-- pg_get_serial_sequence returns NULL and the "mandatory" step would quietly
-- skip that table — leaving exactly the future collision this section exists to
-- prevent, with no error to notice. The loop below RAISES instead, and prints
-- the new value for each sequence so the result is visible rather than assumed.
--
-- This section is idempotent and safe to re-run on its own.
DO $$
DECLARE
  t    text;
  seq  text;
  maxv bigint;
BEGIN
  FOREACH t IN ARRAY ARRAY['workouts','exercises','daily_sleep','daily_steps',
                           'body_metrics','daily_checkins','micro_goals',
                           'workout_templates']
  LOOP
    seq := pg_get_serial_sequence(t, 'id');
    IF seq IS NULL THEN
      RAISE EXCEPTION
        'No sequence found for %.id — setval would have silently done nothing, leaving the id sequence able to collide with cloned rows later. Resolve the owning sequence manually before treating this clone as complete.', t;
    END IF;
    EXECUTE format('SELECT COALESCE(MAX(id), 1) FROM %I', t) INTO maxv;
    PERFORM setval(seq, GREATEST(maxv, 1), true);
    RAISE NOTICE 'sequence % advanced to % (table %)', seq, GREATEST(maxv, 1), t;
  END LOOP;
END $$;
