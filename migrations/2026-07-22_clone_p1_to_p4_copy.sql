-- ============================================================================
-- CLONE PROFILE 1 -> PROFILE 4  ·  STEP 2 of 3: COPY
-- ============================================================================
-- WHAT THIS DOES
--   Clones profile 1's training data onto profile 4 so the Engine v2 planner,
--   progression-state builder, dossier builder and gap-decay logic have real
--   signal to reason about. Data operation only — no application code, no
--   prompt changes, no v1 logic touched.
--
-- STATUS: **NOT RUN.** Written by Claude Code, executed manually by Shimmy in
--   the Supabase SQL editor. Never assume it has been run.
--
-- PREREQUISITES
--   1. Baseline query run and output saved (verification file, section A).
--   2. 2026-07-22_clone_p1_to_p4_wipe.sql run to completion, all counts 0.
--   3. Run this file top-to-bottom in ONE execution. Section 0 aborts the whole
--      run if profile 4 is not empty.
--   4. Section 9 (setval) is MANDATORY. Read its comment before skipping it.
--   5. Then run 2026-07-22_clone_p1_to_p4_flags.sql.
--
-- SAFETY CONTRACT
--   * Profile 1 is READ-ONLY throughout: it appears only in `SELECT ... WHERE
--     profile_id = 1` and `FROM profiles WHERE id = 1`. No INSERT, UPDATE or
--     DELETE in this file targets profile 1.
--   * Every write is explicitly scoped to profile 4 / `id = 4`.
--   * No unqualified DELETE. No `profile_id <> 1`.
--
-- ID STRATEGY — deterministic +100000 offset
--   Cloned rows take `id = source_id + 100000`. This makes parent->child
--   mapping pure arithmetic (exercises.workout_id + 100000), needs no temp
--   tables or RETURNING correlation, and makes the whole script reproducible:
--   a wipe + re-run produces byte-identical ids. Profile 1's max workout id is
--   ~110, so the offset leaves ~99,890 ids of headroom.
--
-- IDENTITY HANDLING — universal, resolves itself at run time
--   Some of these tables are `GENERATED ALWAYS AS IDENTITY` (daily_sleep,
--   daily_steps, body_metrics, workout_templates per their documented DDL),
--   others were created ad-hoc in the SQL editor and their identity kind is not
--   recorded anywhere in the repo. `GENERATED ALWAYS` refuses an explicit id
--   unless the INSERT carries OVERRIDING SYSTEM VALUE; serial / GENERATED BY
--   DEFAULT reject that clause. Each INSERT below is therefore built by a DO
--   block that reads information_schema and adds the clause only when the
--   column actually requires it — so the baseline query's result cannot
--   invalidate this script either way.
--
-- SKIPPED ROWS — the 6 malformed-date workouts
--   Profile 1 has 6 workouts whose `date` column holds a TIME STRING, not a
--   date (ids 110 "10:12", 97 "12:52", 95 "13:00", 88 "19:37", 82 "10:07",
--   77 "10:20"). This is a real production data bug — `workouts.date` is a TEXT
--   column, so these values stored without error. They are invisible to every
--   `date >= x` query in the app and have zero child exercise rows. They are
--   excluded here by a shape regex rather than by hardcoded id, so a 7th such
--   row appearing after the audit is also caught. There is NO hardcoded id list
--   in the filter — this matters, because profile 1 keeps growing (its workout
--   count moved 81 -> 82 between the API audit and the Section A1 baseline).
--   The clone therefore takes "however many date-valid workouts profile 1 has
--   at run time", which was 76 of 82 at baseline.
--   Profile 1's rows are NOT repaired and NOT touched. See ROADMAP.md §6.
--
-- COLUMN LISTS
--   workouts/exercises column lists were read off live production rows.
--   The others come from their documented DDL. If any column name is wrong the
--   INSERT fails loudly — it cannot silently drop a column's data.
-- ============================================================================


-- ── 0. GUARD — refuse to run against a non-empty profile 4 ──────────────────
DO $$
DECLARE n bigint;
BEGIN
  SELECT (SELECT count(*) FROM workouts          WHERE profile_id = 4)
       + (SELECT count(*) FROM exercises         WHERE profile_id = 4)
       + (SELECT count(*) FROM daily_sleep       WHERE profile_id = 4)
       + (SELECT count(*) FROM daily_steps       WHERE profile_id = 4)
       + (SELECT count(*) FROM body_metrics      WHERE profile_id = 4)
       + (SELECT count(*) FROM daily_checkins    WHERE profile_id = 4)
       + (SELECT count(*) FROM micro_goals       WHERE profile_id = 4)
       + (SELECT count(*) FROM workout_templates WHERE profile_id = 4)
    INTO n;
  IF n > 0 THEN
    RAISE EXCEPTION
      'Profile 4 still holds % cloneable row(s). Run 2026-07-22_clone_p1_to_p4_wipe.sql first. (Re-running the copy without a wipe would violate UNIQUE(profile_id,date) on daily_sleep/daily_steps/body_metrics/daily_checkins and duplicate the +100000 ids.)', n;
  END IF;
END $$;


-- ── 1. workouts ─────────────────────────────────────────────────────────────
-- wearable_activity_id is forced to NULL: it carries a UNIQUE partial index and
-- profile 1 had 46 non-null values at audit time (and may have more now), so a
-- verbatim copy is a guaranteed constraint violation. wearable_data IS kept — it holds
-- avg/peak HR, calories, zones and duration_minutes (real autoregulator signal)
-- and contains no credentials.
-- Dates are copied VERBATIM. Gap-decay, "stalled >3 weeks" and "untouched
-- >6 weeks" are all relative to today; shifting or compressing dates would
-- destroy exactly the signal this clone exists to produce.
DO $$
DECLARE ov text;
BEGIN
  SELECT CASE WHEN identity_generation = 'ALWAYS' THEN 'OVERRIDING SYSTEM VALUE' ELSE '' END
    INTO ov
  FROM information_schema.columns
  WHERE table_schema = 'public' AND table_name = 'workouts' AND column_name = 'id';

  EXECUTE format($f$
    INSERT INTO workouts
      (id, profile_id, date, type, notes, done, mobility, med, ts,
       wearable_data, wearable_activity_id)
    %s
    SELECT w.id + 100000, 4, w.date, w.type, w.notes, w.done, w.mobility, w.med, w.ts,
           w.wearable_data, NULL
    FROM workouts w
    WHERE w.profile_id = 1
      AND w.date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
  $f$, COALESCE(ov, ''));
END $$;


-- ── 2. exercises ────────────────────────────────────────────────────────────
-- workout_id is remapped by the same +100000 offset. Rows with a NULL
-- workout_id (extract-exercises can insert one) copy through as NULL, which is
-- always FK-valid. The EXISTS guard means an exercise can only land if its
-- parent workout actually cloned — belt-and-braces against the 6 skipped
-- workouts (audit measured 0 exercise rows under them, so this should be a
-- no-op, but it makes the FK guarantee structural rather than assumed).
DO $$
DECLARE ov text;
BEGIN
  SELECT CASE WHEN identity_generation = 'ALWAYS' THEN 'OVERRIDING SYSTEM VALUE' ELSE '' END
    INTO ov
  FROM information_schema.columns
  WHERE table_schema = 'public' AND table_name = 'exercises' AND column_name = 'id';

  EXECUTE format($f$
    INSERT INTO exercises
      (id, profile_id, workout_id, date, name, category, main_category, subcategory,
       sets, reps, weight_lbs, distance_miles, duration_minutes,
       notes, raw_text, created_at)
    %s
    SELECT e.id + 100000, 4,
           CASE WHEN e.workout_id IS NULL THEN NULL ELSE e.workout_id + 100000 END,
           e.date, e.name, e.category, e.main_category, e.subcategory,
           e.sets, e.reps, e.weight_lbs, e.distance_miles, e.duration_minutes,
           e.notes, e.raw_text, e.created_at
    FROM exercises e
    WHERE e.profile_id = 1
      AND (e.workout_id IS NULL
           OR EXISTS (SELECT 1 FROM workouts w4
                      WHERE w4.id = e.workout_id + 100000 AND w4.profile_id = 4))
  $f$, COALESCE(ov, ''));
END $$;


